# PlatformIO pre-build script: writes include/fw_version.h with the git commit,
# for the details page. "+" after the hash means the firmware files had
# uncommitted changes. The header is only rewritten when the version changes,
# so it doesn't force a rebuild every time.
import os
import subprocess

Import("env")  # noqa: F821 (provided by PlatformIO)

project = env.subst("$PROJECT_DIR")  # noqa: F821


def git(*args):
    return subprocess.run(["git", *args], cwd=project, capture_output=True, text=True)


try:
    head = git("rev-parse", "--short=7", "HEAD")
    version = head.stdout.strip() if head.returncode == 0 else "unknown"
    # Only the firmware's own files count, not the app or docs.
    dirty = git("status", "--porcelain", "--", "src", "include", "platformio.ini")
    if dirty.returncode == 0 and dirty.stdout.strip():
        version += "+"
except OSError:
    version = "unknown"

path = os.path.join(project, "include", "fw_version.h")
text = '#pragma once\n// Generated by tools/fw_version.py. Not in git.\n#define FW_VERSION "%s"\n' % version
try:
    old = open(path, encoding="utf-8").read()
except OSError:
    old = ""
if old != text:
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
print("Firmware version:", version)
